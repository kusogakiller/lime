/* Minimal avconfig.h stub for AST-parsing FFmpeg public headers with clang.
   Real avconfig.h is generated by configure. This provides the subset of
   architecture and HAVE macros that FFmpeg public headers reference under
   HAVE_AV_CONFIG_H guards (skipped when that macro is undefined). Enough to
   let clang -fsyntax-only parse avutil.h / avcodec.h / avformat.h. */
#ifndef AVUTIL_AVCONFIG_H
#define AVUTIL_AVCONFIG_H

#define AV_HAVE_BIGENDIAN 0
#define AV_HAVE_FAST_64BIT 1
#define AV_HAVE_UNALIGNED 1
#define AV_HAVE_ALIGNED_STACK 1

#define ARCH_X86 1
#define ARCH_X86_64 1

#define HAVE_FAST_64BIT 1

#endif /* AVUTIL_AVCONFIG_H */
