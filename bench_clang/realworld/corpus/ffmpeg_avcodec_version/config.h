/* Minimal config.h stub for compiling FFmpeg libavutil with clang on Windows.
   Real config.h is generated by configure. Defines the subset of HAVE/ARCH/CONFIG
   macros libavutil core .c files test, for x86-64 / Windows / no optional features. */
#ifndef FFMPEG_CONFIG_H_STUB
#define FFMPEG_CONFIG_H_STUB

#define ARCH_X86       1
#define ARCH_X86_64    1
#define HAVE_FAST_64BIT 1
#define HAVE_ALIGNED_STACK 1

#define HAVE_BIGENDIAN 0
#define AV_HAVE_BIGENDIAN 0
#define AV_HAVE_FAST_64BIT 1
#define AV_HAVE_UNALIGNED 1
#define AV_HAVE_ALIGNED_STACK 1

#define HAVE_ALIGNED_MALLOC   0
#define HAVE_MALLOC_H        1
#define HAVE_MEMALIGN         0
#define HAVE_POSIX_MEMALIGN   0
#define HAVE_SIMD_ALIGN_32    0
#define HAVE_MMX_INLINE       0
#define HAVE_SSE              0
#define CONFIG_MEMORY_POISONING 0
#define HAVE_THREADS         0

#define CONFIG_GPL        0
#define CONFIG_NONFREE    0
#define CONFIG_LIBRARY     1

#define SIZEOF_INT        4
#define SIZEOF_LONG       4
#define SIZEOF_LONG_LONG  8
#define SIZEOF_SHORT      2
#define SIZEOF_VOID_P     8
#define SIZEOF_SIZE_T     8
#define SIZEOF_INT64_T    8

#define FFMPEG_CONFIGURATION "--enable-static (charger smoke stub)"
#define FFMPEG_VERSION "8.1.2"
#define FFMPEG_LICENSE "LGPL version 2.1 or later"

#endif /* FFMPEG_CONFIG_H_STUB */

/* charger smoke: MSVC UCRT provides C99-compliant snprintf/vsnprintf,
   so FFmpeg must use them instead of defining its own (avoids duplicate
   snprintf across TUs). Generic FFmpeg configure flag, no library hack. */
#define HAVE_SNPRINTF    1
#define HAVE_VSNPRINTF   1
